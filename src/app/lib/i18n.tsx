export const DICTIONARIES: Record<Lang, Dict> = { en, pt };

/** Idioma inicial: português se o navegador estiver em português */
export const detectLang = (): Lang =>
  typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("pt") ? "pt" : "en";

const I18nContext = createContext<Dict>(en);

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  return <I18nContext.Provider value={DICTIONARIES[lang] ?? en}>{children}</I18nContext.Provider>;
}

export const useT = () => useContext(I18nContext);
